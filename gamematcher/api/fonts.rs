//! Build-time font rasterizer (included by build.rs): turns the bundled
//! Atkinson Hyperlegible TTFs into 4-bit anti-aliased glyph atlases for the
//! board's screen, as a generated `fonts.rs`. Only the sizes and characters
//! the cards use, so it costs tens of KB of flash, not the 110 KB of TTFs,
//! and the board never parses a font.
use std::fmt::Write as _;
use std::path::Path;

/// (name, file, pixel size, characters).
const FACES: &[(&str, &str, f32, &str)] = &[
    ("SMALL", "AtkinsonHyperlegible-Regular.ttf", 12.0, TEXT),
    ("BODY", "AtkinsonHyperlegible-Regular.ttf", 14.0, TEXT),
    ("BOLD", "AtkinsonHyperlegible-Bold.ttf", 15.0, TEXT),
    ("MID", "AtkinsonHyperlegible-Bold.ttf", 18.0, TEXT),
    ("TITLE", "AtkinsonHyperlegible-Bold.ttf", 22.0, TEXT),
    (
        "HUGE",
        "AtkinsonHyperlegible-Bold.ttf",
        46.0,
        "0123456789: ",
    ),
];

/// Printable ASCII plus what names and plan titles tend to need.
const TEXT: &str = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~\
·–—‘’“”…•éèêëáàâäåíìîïóòôöõúùûüñçÉÈÁÀÖÜÑÇ";

pub fn generate(root: &Path, out: &Path) {
    let mut code =
        String::from("// Generated by build.rs from fonts/*.ttf (SIL OFL 1.1). Do not edit.\n");
    for (name, file, px, chars) in FACES {
        let path = root.join("fonts").join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let font = fontdue::Font::from_bytes(bytes, fontdue::FontSettings::default())
            .unwrap_or_else(|e| panic!("{file}: {e}"));
        let line = font
            .horizontal_line_metrics(*px)
            .expect("horizontal metrics");
        let mut glyphs = String::new();
        let mut bits: Vec<u8> = Vec::new();
        let mut sorted: Vec<char> = chars.chars().collect();
        sorted.sort_unstable();
        sorted.dedup();
        for ch in sorted {
            if ch != ' ' && font.lookup_glyph_index(ch) == 0 {
                continue; // not in the font
            }
            let (m, coverage) = font.rasterize(ch, *px);
            let offset = bits.len();
            // Two pixels per byte, 4 bits of coverage each, high nibble first.
            for pair in coverage.chunks(2) {
                let hi = pair[0] >> 4;
                let lo = pair.get(1).map_or(0, |v| v >> 4);
                bits.push(hi << 4 | lo);
            }
            // top: rows from the baseline up to the bitmap's top edge.
            let top = m.ymin + m.height as i32;
            writeln!(
                glyphs,
                "    Glyph {{ ch: {:?}, w: {}, h: {}, left: {}, top: {}, advance: {}, offset: {} }},",
                ch,
                m.width,
                m.height,
                m.xmin,
                top,
                m.advance_width.round() as u32,
                offset
            )
            .unwrap();
        }
        writeln!(
            code,
            "pub static {name}: Face = Face {{\n  ascent: {}, descent: {}, line: {},\n  glyphs: &[\n{glyphs}  ],\n  bits: &{:?},\n}};",
            line.ascent.round() as i32,
            line.descent.round() as i32,
            line.new_line_size.round() as u32,
            bits
        )
        .unwrap();
    }
    std::fs::write(out.join("fonts.rs"), code).unwrap();
}
