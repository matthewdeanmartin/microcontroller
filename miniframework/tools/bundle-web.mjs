// Turns a built Angular app into `assets.rs` for an app to `include!`.
//
//   node tools/bundle-web.mjs <dist/browser dir> <output dir>
//
// Every file is stored gzip-compressed only (level 9): browsers always
// accept gzip, and on a 4 MiB board flash is the scarce thing. The server
// sends the gzip bytes as they are (Content-Encoding: gzip), so serving a
// file costs no CPU. ETags are content hashes; Angular's hashed file names
// are marked immutable (cached for a year).
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { extname, relative, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const [input, output] = process.argv.slice(2).map((p) => p && resolve(p));
if (!input || !output) {
  console.error('Usage: node tools/bundle-web.mjs <dist/browser dir> <output dir>');
  process.exit(2);
}

const types = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
};

rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
const entries = [];
let rawTotal = 0;
let gzTotal = 0;

function walk(dir) {
  for (const item of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = resolve(dir, item.name);
    if (item.isDirectory()) {
      walk(path);
      continue;
    }
    const name = relative(input, path).replaceAll('\\', '/');
    const mime = types[extname(name)];
    if (!/^[A-Za-z0-9_./-]+$/.test(name) || !mime) throw new Error(`Unsupported asset: ${name}`);
    const data = readFileSync(path);
    const gz = gzipSync(data, { level: 9 });
    const id = entries.length;
    writeFileSync(resolve(output, `${id}.gz`), gz);
    rawTotal += data.length;
    gzTotal += gz.length;
    const etag = 'W/"' + createHash('sha256').update(data).digest('hex').slice(0, 32) + '"';
    const file = JSON.stringify(resolve(output, `${id}.gz`).replaceAll('\\', '/'));
    const immutable = /-[A-Za-z0-9_]{8,}\.(js|css|mjs)$/.test(name);
    entries.push(
      `    Asset { path: ${JSON.stringify('/' + name)}, mime: ${JSON.stringify(mime)}, raw: b"", gzip: include_bytes!(${file}), etag: ${JSON.stringify(etag)}, immutable: ${immutable} },`,
    );
  }
}

walk(input);
if (!entries.some((e) => e.includes('path: "/index.html"'))) throw new Error(`No index.html in ${input}`);
writeFileSync(
  resolve(output, 'assets.rs'),
  `// Generated by tools/bundle-web.mjs from ${relative(output, input).replaceAll('\\', '/')}. Do not edit.\nstatic ASSETS: &[Asset] = &[\n${entries.join('\n')}\n];\n`,
);
console.log(`Bundled ${entries.length} files: ${(rawTotal / 1024).toFixed(0)} KiB, ${(gzTotal / 1024).toFixed(0)} KiB gzipped, into ${output}`);
