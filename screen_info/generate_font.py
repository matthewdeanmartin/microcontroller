"""Generate the app's small, fixed 5x7 ASCII font (no external font dependency)."""
from pathlib import Path

# Each column stores seven pixels, top to bottom in the low bits.
glyphs = {
    ' ': [0,0,0,0,0], '!':[0,0,95,0,0], '%':[99,19,8,100,99],
    '&':[54,73,85,34,80], '(':[0,28,34,65,0], ')':[0,65,34,28,0],
    '+':[8,8,62,8,8], ',':[0,80,48,0,0], '-':[8,8,8,8,8],
    '.':[0,96,96,0,0], '/':[32,16,8,4,2], ':':[0,54,54,0,0],
    '?':[2,1,81,9,6], '=':[20,20,20,20,20], '_':[64,64,64,64,64],
    '0':[62,81,73,69,62], '1':[0,66,127,64,0], '2':[66,97,81,73,70],
    '3':[33,65,69,75,49], '4':[24,20,18,127,16], '5':[39,69,69,69,57],
    '6':[60,74,73,73,48], '7':[1,113,9,5,3], '8':[54,73,73,73,54],
    '9':[6,73,73,41,30], 'A':[126,17,17,17,126], 'B':[127,73,73,73,54],
    'C':[62,65,65,65,34], 'D':[127,65,65,34,28], 'E':[127,73,73,73,65],
    'F':[127,9,9,9,1], 'G':[62,65,73,73,122], 'H':[127,8,8,8,127],
    'I':[0,65,127,65,0], 'J':[32,64,65,63,1], 'K':[127,8,20,34,65],
    'L':[127,64,64,64,64], 'M':[127,2,12,2,127], 'N':[127,4,8,16,127],
    'O':[62,65,65,65,62], 'P':[127,9,9,9,6], 'Q':[62,65,81,33,94],
    'R':[127,9,25,41,70], 'S':[70,73,73,73,49], 'T':[1,1,127,1,1],
    'U':[63,64,64,64,63], 'V':[31,32,64,32,31], 'W':[63,64,56,64,63],
    'X':[99,20,8,20,99], 'Y':[7,8,112,8,7], 'Z':[97,81,73,69,67],
}
rows = []
for code in range(32,127):
    columns = glyphs.get(chr(code).upper(), glyphs['?'])
    rows.append([sum(((column >> (y//2)) & 1) << (x+1) for x,column in enumerate(columns)) for y in range(14)])
Path(__file__).with_name('main').joinpath('font.h').write_text(
    '// Generated by generate_font.py; 5x7 glyphs in 8x14 cells.\n'
    'static const unsigned char font[95][14]={\n'
    + ',\n'.join('{'+','.join(map(str,row))+'}' for row in rows) + '\n};\n'
)
